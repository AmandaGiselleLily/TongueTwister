import os
import glob
import matplotlib.pyplot as plt

# Paths
tsv_path = "/home/alily/Documents/GitHub/TongueTwister/Analysis/alldat/sub_06_alldat.tsv"
wav_folder = "/home/alily/Documents/GitHub/TongueTwister/Experiments/TT1/data/sub-06"
output_folder = "/home/alily/Documents/GitHub/TongueTwister/Analysis"

# Automatically find all WAV files in the folder
wav_files = sorted(glob.glob(os.path.join(wav_folder, "*.wav")))
print(f"Found {len(wav_files)} WAV files.")

# Plot n WAV files in each figure
plots_per_figure = 10

for start_index in range(0, len(wav_files), plots_per_figure):
    # Get the next 5 WAV files
    current_wav_files = wav_files[start_index:start_index + plots_per_figure]
    number_of_plots = len(current_wav_files)
    # Create subplots
    fig, axes = plt.subplots(number_of_plots,1,figsize=(16, 4 * number_of_plots))
    # If only one subplot exists
    if number_of_plots == 1:
        axes = [axes]
    
    # Process each WAV using your existing function
    for new_ax, wav_path in zip(axes, current_wav_files):
        # Call your existing function
        temp_fig, temp_ax = plot_wav_borders(tsv_path=tsv_path, wav_path=wav_path,
            save_plot=False, show_plot=False)

        # Copy all lines to the new subplot
        for line in temp_ax.get_lines():
            new_ax.plot(line.get_xdata(), line.get_ydata(),
                color=line.get_color(), linestyle=line.get_linestyle(),
                linewidth=line.get_linewidth(), alpha=line.get_alpha(),
                label=line.get_label())

        # Copy title and limits
        new_ax.set_title(temp_ax.get_title())
        new_ax.set_xlabel("Time (seconds)")
        new_ax.set_ylabel("Amplitude")
        new_ax.set_xlim(temp_ax.get_xlim())
        new_ax.grid(True, alpha=0.2)
        new_ax.legend()

        # Close temporary figure
        plt.close(temp_fig)
    # Final formatting
    plt.tight_layout()

    # Save this group of 5
    os.makedirs(output_folder, exist_ok=True) 
    figure_number = start_index // plots_per_figure + 1

    output_path = os.path.join(output_folder,
        f"border_plots_{figure_number}.png")

    fig.savefig(output_path, dpi=300, bbox_inches="tight")
    print(f"Saved: {output_path}")
    plt.show()







